function renderAttributionLinks(asset: InspirationAsset): string {
  const rows: string[] = [];
  if (asset.sourceUrl !== null) {
    rows.push(`<dt>Source</dt><dd><a href="${escapeInspirationHtml(asset.sourceUrl)}" rel="noopener noreferrer" target="_blank">Open source</a></dd>`);
  }
  if (asset.licenseUrl !== null) {
    rows.push(`<dt>License</dt><dd><a href="${escapeInspirationHtml(asset.licenseUrl)}" rel="noopener noreferrer" target="_blank">Open license</a></dd>`);
  }
  if (asset.retrievedAt !== null) rows.push(`<dt>Retrieved</dt><dd>${escapeInspirationHtml(asset.retrievedAt)}</dd>`);
  return rows.length === 0 ? '' : `            ${rows.join('\n            ')}`;
}

function percentage(value: number): string {
  // Region bounds are validated in contract.ts. Rounding remains deterministic
  // and keeps the generated source readable rather than serialising binary FP.
  return String(Math.round(value * 10_000) / 100);
}

function formatPercent(value: number): string {
  return String(Math.round(value * 10_000) / 100);
}

/** A downward-rounded percentage suitable for an asset-height container unit. */
function containmentPercentage(value: number): string {
  return String(Math.floor(value * 100_000_000) / 1_000_000);
}

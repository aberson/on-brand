/** Escape text and attributes; all dynamic prose goes through this one seam. */
export function escapeInspirationHtml(value: string): string {
  let out = '';
  for (let index = 0; index < value.length; index++) {
    const char = value[index]!;
    if (char === '&') out += '&amp;';
    else if (char === '<') out += '&lt;';
    else if (char === '>') out += '&gt;';
    else if (char === '"') out += '&quot;';
    else if (char === "'") out += '&#39;';
    else out += char;
  }
  return out;
}


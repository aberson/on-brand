/**
 * manifest.json — provenance + the stale-dist drift anchor (plan.md §3.1/§3.2).
 *
 * The manifest records: onbrand version, schema version, a SHA-256 over the
 * RESOLVED source inputs (tokens.json + the resolved extends chain +
 * modes.dark.json), the emitters actually run, LLM status, and a timestamp.
 *
 * Determinism contract (full rationale in
 * docs/findings/style-dictionary-decision.md § Manifest determinism contract):
 *   - Source hashing is a pure function of source CONTENT: each file's bytes
 *     are CRLF-normalized to LF before hashing so a git autocrlf checkout
 *     cannot flip the hash, then combined in a fixed order.
 *   - `timestamp` records when the recorded sourceHash LAST CHANGED, not when
 *     the build ran: if the previous dist/manifest.json carries the same
 *     sourceHash, its timestamp is preserved byte-for-byte. Two consecutive
 *     identical builds are therefore byte-identical, and the manifest changes
 *     iff the sources change.
 *   - `outputs` is PER-OUTPUT provenance: for every emitted dist file, the
 *     sourceHash that was current when THAT file was last regenerated.
 *     Entries for outputs not regenerated by a run (an `--emit` subset build)
 *     are carried forward from the previous manifest — so the Step-5 drift
 *     guard can flag any single output whose recorded hash mismatches the
 *     current sources, even when the top-level sourceHash is fresh.
 *
 * Source labels (`sources[].path`) are IDENTITY KEYS, not openable paths —
 * see ManifestSource.path below.
 */

import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { SCHEMA_VERSION, isPlainObject, isUnsafeName } from '../schema/types.ts';
import { packageRoot } from '../schema/resolve.ts';

/** LLM involvement in producing the sources. `build` never runs an LLM ('none');
 * from-url (Step 12) passes 'used' or 'skipped' through (plan.md §6). */
export type LlmStatus = 'none' | 'used' | 'skipped';

export interface ManifestSource {
  /**
   * IDENTITY KEY for the source — an opaque, machine-independent label, NOT
   * necessarily an openable path (Step 5's drift check and any other
   * consumer must treat it as a key). Shapes (built by compile.ts
   * sourceLabel()):
   *   - project-local files: brand/-relative, forward slashes
   *     ("tokens.json", "../base-tokens.json");
   *   - files resolved inside the on-brand install (preset extends targets):
   *     "onbrand:<package-relative path>" — stable across machines/installs;
   *   - case-normalized (lowercased) on win32 only, where the filesystem is
   *     case-insensitive (mirrors resolve.ts cycleKey()); exact casing is
   *     preserved on case-sensitive filesystems.
   */
  path: string;
  sha256: string;
}

/** A single input that explains an output-specific freshness digest. */
export interface ManifestOutputSource {
  /** Stable human/machine label, for example "core" or "asset". */
  label: string;
  /** Brand-relative source identity when there is one; null for a digest row. */
  sourcePath: string | null;
  /** Text inputs normalize CRLF; binary inputs are always exact bytes. */
  kind: 'text-lf' | 'binary' | 'digest';
  /** Lowercase SHA-256 hexadecimal digest. */
  sha256: string;
}

export interface Manifest {
  onbrandVersion: string;
  schemaVersion: number;
  /** Combined SHA-256 over all sources (order-sensitive, content-derived). */
  sourceHash: string;
  sources: ManifestSource[];
  /** Emitters actually run THIS build (skipped/not-yet-built ones excluded). */
  emitters: string[];
  /**
   * Per-output provenance: dist/-relative path -> the sourceHash current when
   * that file was last regenerated (carried forward across subset builds).
   * Keys sorted lexicographically for byte-determinism.
   */
  outputs: Record<string, string>;
  /**
   * Optional output-specific provenance: broader input freshness for the
   * explanation, or an exact-content digest binding for the specimen. Kept
   * absent for ordinary emitter outputs so their manifests stay byte-compatible.
   */
  outputSources?: Record<string, ManifestOutputSource[]>;
  llm: LlmStatus;
  /** ISO 8601 UTC; when sourceHash last changed (see determinism contract). */
  timestamp: string;
}

const STRICT_MANIFEST_KEYS = [
  'onbrandVersion',
  'schemaVersion',
  'sourceHash',
  'sources',
  'emitters',
  'outputs',
  'outputSources',
  'llm',
  'timestamp',
] as const;

/** Read the on-brand version from package.json (one source of truth). */
export function onbrandVersion(): string {
  const pkg = JSON.parse(
    readFileSync(path.join(packageRoot(), 'package.json'), 'utf8'),
  ) as { version?: string };
  return pkg.version ?? '0.0.0';
}

/** SHA-256 hex of a string after CRLF -> LF normalization. */
export function hashContent(content: string): string {
  return createHash('sha256').update(content.replaceAll('\r\n', '\n'), 'utf8').digest('hex');
}

/** SHA-256 of raw bytes. Unlike hashContent this never normalizes CR/LF. */
export function hashBytes(bytes: Uint8Array): string {
  return createHash('sha256').update(bytes).digest('hex');
}

/**
 * Whether a `manifest.outputs` KEY is a clean dist/-relative output path
 * (issue #19 hardening). The manifest merge (buildManifest) drops any carried-
 * forward key that fails this, and the Step-5 drift check (src/check/drift.ts)
 * uses it to refuse to stat a key that would escape dist/. A clean key is a
 * forward-slash relative path whose every segment is a real name:
 *   - not empty, not absolute (no leading "/", no "C:" drive prefix),
 *   - no backslashes (Windows-path shapes are not dist/-relative keys),
 *   - no "." / ".." segments (traversal) and no reserved object-model names,
 *   - no control bytes.
 * Char-code comparisons, not a regex class (repo authoring-hazard rule).
 */
export function isCleanOutputKey(key: string): boolean {
  if (key.length === 0) return false;
  // Reject a Windows drive prefix ("C:...") without a regex escape class.
  const c0 = key.charCodeAt(0);
  const isAlpha = (c0 >= 65 && c0 <= 90) || (c0 >= 97 && c0 <= 122);
  if (isAlpha && key.charCodeAt(1) === 58 /* ':' */) return false;
  for (let i = 0; i < key.length; i++) {
    const code = key.charCodeAt(i);
    if (code < 0x20) return false; // control byte
    if (code === 92 /* backslash */) return false;
  }
  const segments = key.split('/');
  for (const seg of segments) {
    if (seg === '' || seg === '.' || seg === '..') return false; // absolute/traversal/empty
    if (isUnsafeName(seg)) return false; // __proto__ / constructor / prototype
  }
  return true;
}

export interface SourceInput {
  /** Identity-key label for the source (see ManifestSource.path for the shapes). */
  relPath: string;
  /** Raw text content (as read from disk). Mutually exclusive with bytes. */
  content?: string;
  /** Raw binary content. Never CR/LF-normalized. */
  bytes?: Uint8Array;
}

export interface SourceHashResult {
  sources: ManifestSource[];
  sourceHash: string;
}

/**
 * Hash each source and combine into one order-sensitive hash. Inputs must be
 * passed in canonical order: tokens.json first, then the extends chain
 * (extender -> deepest base), then modes.dark.json (when present).
 */
export function computeSourceHash(inputs: readonly SourceInput[]): SourceHashResult {
  const sources: ManifestSource[] = inputs.map((input) => ({
    path: input.relPath,
    sha256: sourceInputHash(input),
  }));
  const combined = createHash('sha256');
  for (const source of sources) {
    combined.update(`${source.path}\n${source.sha256}\n`, 'utf8');
  }
  return { sources, sourceHash: combined.digest('hex') };
}

/** Hash one discriminated text/binary source input with an explicit guard. */
export function sourceInputHash(input: SourceInput): string {
  if (typeof input.content === 'string' && input.bytes === undefined) return hashContent(input.content);
  if (input.bytes !== undefined && input.content === undefined) return hashBytes(input.bytes);
  throw new Error(`source ${JSON.stringify(input.relPath)} must provide exactly one of content or bytes`);
}

export interface BuildManifestOptions {
  hash: SourceHashResult;
  emitters: readonly string[];
  /** dist/-relative paths of the files emitted THIS run (manifest.json excluded). */
  outputs: readonly string[];
  /** Per-output freshness digests for outputs emitted this run. */
  outputHashes?: Readonly<Record<string, string>>;
  /** Per-output input provenance for outputs emitted this run. */
  outputSources?: Readonly<Record<string, readonly ManifestOutputSource[]>>;
  /** Explicit known outputs to remove from carried-forward state. */
  omitOutputs?: readonly string[];
  llm?: LlmStatus;
  /** Raw content of the previous dist/manifest.json, when one exists. */
  previousManifestContent?: string;
  /**
   * Prune predicate for CARRIED-FORWARD outputs (issue #19): a previous-
   * manifest output entry is dropped when this returns false (no matching file
   * on disk). Outputs emitted THIS run are never pruned (they were just
   * written). When omitted, no on-disk pruning happens (pure/unit callers).
   */
  carriedOutputExists?: (relPath: string) => boolean;
  /** Sink for merge-time warnings (dropped/pruned outputs.keys). Default: no-op. */
  onWarning?: (message: string) => void;
  /** Injectable clock for tests; defaults to Date.now-based UTC ISO string. */
  now?: () => string;
}

/**
 * Assemble the manifest, preserving the previous timestamp when the source
 * hash is unchanged (the determinism contract above) and merging per-output
 * provenance: outputs emitted this run are stamped with the current
 * sourceHash; previous entries for outputs NOT regenerated this run are
 * carried forward so a subset build can never make a stale output look fresh.
 */
export function buildManifest(options: BuildManifestOptions): Manifest {
  const { hash, emitters } = options;
  const now = options.now ?? (() => new Date().toISOString());
  const previous =
    options.previousManifestContent !== undefined
      ? tryParseManifest(options.previousManifestContent)
      : undefined;
  const warn = options.onWarning ?? (() => {});

  let timestamp = now();
  if (
    previous !== undefined &&
    typeof previous.sourceHash === 'string' &&
    isSha256(previous.sourceHash) &&
    previous.sourceHash === hash.sourceHash &&
    isIsoTimestamp(previous.timestamp)
  ) {
    timestamp = previous.timestamp as string;
  }

  const omitted = new Set(options.omitOutputs ?? []);
  if (options.outputHashes !== undefined && !isPlainObject(options.outputHashes)) {
    throw new Error('manifest.outputs: current digest map is not an object');
  }
  if (options.outputSources !== undefined && !isPlainObject(options.outputSources)) {
    throw new Error('manifest.outputSources: current provenance map is not an object');
  }
  const merged: Record<string, string> = {};
  if (previous !== undefined && isPlainObject(previous.outputs)) {
    for (const [key, value] of Object.entries(previous.outputs)) {
      if (omitted.has(key)) continue;
      if (typeof value !== 'string') {
        warn(`manifest.outputs: dropped ${JSON.stringify(key)} (digest is not a string)`);
        continue;
      }
      // #19: validate carried-forward keys as clean dist/-relative paths —
      // reject absolute / traversal / non-emitter-shaped keys outright so the
      // drift check can never be handed a key that escapes dist/.
      if (!isCleanOutputKey(key)) {
        warn(`manifest.outputs: dropped key ${JSON.stringify(key)} (not a clean dist/-relative path)`);
        continue;
      }
      if (!isSha256(value)) {
        warn(`manifest.outputs: dropped ${JSON.stringify(key)} (not a lowercase SHA-256 digest)`);
        continue;
      }
      // #19: prune entries whose file is gone from disk (findings-doc note).
      if (options.carriedOutputExists !== undefined && !options.carriedOutputExists(key)) {
        warn(`manifest.outputs: pruned ${JSON.stringify(key)} (no matching file in dist/)`);
        continue;
      }
      merged[key] = value;
    }
  } else if (previous?.outputs !== undefined) {
    warn('manifest.outputs: dropped invalid carried output map');
  }

  const currentOutputs = new Set<string>();
  for (const relPath of options.outputs) {
    if (!isCleanOutputKey(relPath)) {
      throw new Error(
        `manifest.outputs: current output ${JSON.stringify(relPath)} is not a clean dist/-relative path`,
      );
    }
    currentOutputs.add(relPath);
  }
  const currentHashes = new Map<string, string>();
  for (const [key, digest] of Object.entries(options.outputHashes ?? {})) {
    if (!currentOutputs.has(key)) {
      throw new Error(
        `manifest.outputs: current digest names non-emitted output ${JSON.stringify(key)}`,
      );
    }
    if (typeof digest !== 'string' || !isSha256(digest)) {
      throw new Error(
        `manifest.outputs: current digest for ${JSON.stringify(key)} is not a lowercase SHA-256 digest`,
      );
    }
    currentHashes.set(key, digest);
  }
  for (const relPath of options.outputs) {
    merged[relPath] = currentHashes.get(relPath) ?? hash.sourceHash;
  }
  const outputs: Record<string, string> = {};
  for (const key of Object.keys(merged).sort()) {
    outputs[key] = merged[key]!;
  }

  const carriedSources = previous !== undefined && isPlainObject(previous.outputSources)
    ? previous.outputSources
    : undefined;
  if (previous?.outputSources !== undefined && carriedSources === undefined) {
    warn('manifest.outputSources: dropped invalid carried provenance map');
  }
  const repairedCarriedSources: Record<string, ManifestOutputSource[]> = {};
  for (const [key, candidate] of Object.entries(carriedSources ?? {})) {
    const valid = validateOutputSources(candidate);
    if (valid === undefined) {
      warn(`manifest.outputSources: dropped invalid carried provenance for ${JSON.stringify(key)}`);
      continue;
    }
    repairedCarriedSources[key] = valid;
  }
  const currentSources: Record<string, ManifestOutputSource[]> = {};
  for (const [key, candidate] of Object.entries(options.outputSources ?? {})) {
    if (!currentOutputs.has(key)) {
      throw new Error(
        `manifest.outputSources: current provenance names non-emitted output ${JSON.stringify(key)}`,
      );
    }
    const valid = validateOutputSources(candidate);
    if (valid === undefined) {
      throw new Error(`manifest.outputSources: invalid current provenance for ${JSON.stringify(key)}`);
    }
    currentSources[key] = valid;
  }
  const outputSources: Record<string, ManifestOutputSource[]> = {};
  for (const key of Object.keys(outputs).sort()) {
    const current = currentSources[key];
    // Regeneration replaces the complete current provenance for that output.
    // Prior rows carry only when the output itself was not emitted this run.
    const candidate = current ?? (currentOutputs.has(key) ? undefined : repairedCarriedSources[key]);
    if (candidate === undefined) continue;
    outputSources[key] = candidate;
  }

  const manifest: Manifest = {
    onbrandVersion: onbrandVersion(),
    schemaVersion: SCHEMA_VERSION,
    sourceHash: hash.sourceHash,
    sources: hash.sources,
    emitters: [...emitters],
    outputs,
    ...(Object.keys(outputSources).length > 0 ? { outputSources } : {}),
    llm: options.llm ?? 'none',
    timestamp,
  };
  // A parseable-but-corrupt prior envelope is repair input, never authority.
  // Validate the reconstructed bytes with the same strict consumer contract
  // used by recorders before allowing compileBrand to publish them.
  return parseStrictManifest(renderManifest(manifest));
}

function isSha256(value: string): boolean {
  if (value.length !== 64) return false;
  for (let i = 0; i < value.length; i++) {
    const code = value.charCodeAt(i);
    const hex =
      (code >= 48 && code <= 57) ||
      (code >= 97 && code <= 102);
    if (!hex) return false;
  }
  return true;
}

function validateOutputSources(value: unknown): ManifestOutputSource[] | undefined {
  if (!Array.isArray(value) || value.length === 0 || value.length > 8) return undefined;
  const out: ManifestOutputSource[] = [];
  for (const row of value) {
    if (!isPlainObject(row) || !hasOnlyKeys(row, ['label', 'sourcePath', 'kind', 'sha256'])) {
      return undefined;
    }
    const label = row['label'];
    const sourcePath = row['sourcePath'];
    const kind = row['kind'];
    const sha256 = row['sha256'];
    if (
      typeof label !== 'string' ||
      label.length === 0 ||
      label.length > 80 ||
      hasControlCharacter(label) ||
      (typeof sourcePath !== 'string' && sourcePath !== null) ||
      (typeof sourcePath === 'string' && (sourcePath.length > 1_024 || hasControlCharacter(sourcePath))) ||
      (kind !== 'text-lf' && kind !== 'binary' && kind !== 'digest') ||
      typeof sha256 !== 'string' ||
      !isSha256(sha256)
    ) {
      return undefined;
    }
    out.push({ label, sourcePath, kind, sha256 });
  }
  return out;
}

/**
 * Parse the complete current manifest contract without repairing or dropping
 * malformed fields. Generated-view recording uses this before mutating a
 * manifest so a partial, stale, or hand-corrupted envelope can never be
 * certified by adding one apparently current output row.
 */
export function parseStrictManifest(content: string): Manifest {
  let parsed: unknown;
  try {
    parsed = JSON.parse(content) as unknown;
  } catch {
    throw new Error('cannot record generated-view provenance: dist/manifest.json is invalid JSON');
  }
  if (!isStrictManifest(parsed)) {
    throw new Error('cannot record generated-view provenance: dist/manifest.json has an invalid manifest envelope');
  }
  return parsed;
}

function isStrictManifest(value: unknown): value is Manifest {
  if (!isPlainObject(value) || !hasOnlyKeys(value, STRICT_MANIFEST_KEYS)) return false;
  const sourceHash = value['sourceHash'];
  if (
    typeof value['onbrandVersion'] !== 'string' ||
    value['onbrandVersion'].length === 0 ||
    value['onbrandVersion'].length > 80 ||
    hasControlCharacter(value['onbrandVersion']) ||
    value['schemaVersion'] !== SCHEMA_VERSION ||
    typeof sourceHash !== 'string' ||
    !isSha256(sourceHash) ||
    (value['llm'] !== 'none' && value['llm'] !== 'used' && value['llm'] !== 'skipped') ||
    !isIsoTimestamp(value['timestamp'])
  ) {
    return false;
  }

  const sources = value['sources'];
  if (!Array.isArray(sources) || sources.length === 0) return false;
  const combined = createHash('sha256');
  const sourcePaths = new Set<string>();
  for (const source of sources) {
    if (!isPlainObject(source) || !hasOnlyKeys(source, ['path', 'sha256'])) return false;
    const sourcePath = source['path'];
    const sha256 = source['sha256'];
    if (
      typeof sourcePath !== 'string' ||
      sourcePath.length === 0 ||
      sourcePath.length > 1_024 ||
      hasControlCharacter(sourcePath) ||
      sourcePaths.has(sourcePath) ||
      typeof sha256 !== 'string' ||
      !isSha256(sha256)
    ) {
      return false;
    }
    sourcePaths.add(sourcePath);
    combined.update(`${sourcePath}\n${sha256}\n`, 'utf8');
  }
  if (combined.digest('hex') !== sourceHash) return false;

  const emitters = value['emitters'];
  if (
    !Array.isArray(emitters) ||
    emitters.some((emitter) => (
      typeof emitter !== 'string' || emitter.length === 0 || emitter.length > 80 || hasControlCharacter(emitter)
    )) ||
    new Set(emitters).size !== emitters.length
  ) {
    return false;
  }

  const outputs = value['outputs'];
  if (!isPlainObject(outputs)) return false;
  for (const [key, sha256] of Object.entries(outputs)) {
    if (!isCleanOutputKey(key) || typeof sha256 !== 'string' || !isSha256(sha256)) return false;
  }

  const outputSources = value['outputSources'];
  if (outputSources === undefined) return true;
  if (!isPlainObject(outputSources)) return false;
  for (const [key, rows] of Object.entries(outputSources)) {
    if (!Object.hasOwn(outputs, key) || validateOutputSources(rows) === undefined) return false;
  }
  return true;
}

function hasOnlyKeys(value: Record<string, unknown>, allowed: readonly string[]): boolean {
  return Object.keys(value).every((key) => allowed.includes(key));
}

function isIsoTimestamp(value: unknown): boolean {
  if (typeof value !== 'string') return false;
  try {
    return new Date(value).toISOString() === value;
  } catch {
    return false;
  }
}

function hasControlCharacter(value: string): boolean {
  for (let index = 0; index < value.length; index++) {
    const code = value.charCodeAt(index);
    if (code < 0x20 || code === 0x7f) return true;
  }
  return false;
}

/** Stable rendering: fixed key order (construction order), 2-space indent, LF, trailing newline. */
export function renderManifest(manifest: Manifest): string {
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

/**
 * Apply a small, output-only manifest mutation without changing the core
 * source hash, timestamp, or emitter record. Generated views use this after
 * their own atomic write: failure leaves any earlier provenance unchanged
 * rather than falsely certifying the new write. The function is deliberately
 * conservative and refuses a malformed manifest instead of inventing one.
 */
export function mutateManifestOutputs(
  content: string,
  mutation: {
    set?: Readonly<Record<string, { sha256: string; sources?: readonly ManifestOutputSource[] }>>;
    remove?: readonly string[];
  },
): Manifest {
  const parsed = parseStrictManifest(content);
  const outputs: Record<string, string> = {};
  for (const [key, value] of Object.entries(parsed.outputs)) {
    outputs[key] = value;
  }
  const rawSources = parsed.outputSources ?? {};
  const outputSources: Record<string, ManifestOutputSource[]> = {};
  for (const [key, value] of Object.entries(rawSources)) {
    const validated = validateOutputSources(value);
    if (validated !== undefined && Object.hasOwn(outputs, key)) outputSources[key] = validated;
  }
  for (const key of mutation.remove ?? []) {
    if (!isCleanOutputKey(key)) throw new Error(`cannot remove unsafe generated output ${JSON.stringify(key)}`);
    delete outputs[key];
    delete outputSources[key];
  }
  for (const [key, change] of Object.entries(mutation.set ?? {})) {
    if (!isCleanOutputKey(key) || !isSha256(change.sha256)) {
      throw new Error(`cannot record invalid generated output ${JSON.stringify(key)}`);
    }
    outputs[key] = change.sha256;
    if (change.sources === undefined) {
      delete outputSources[key];
    } else {
      const valid = validateOutputSources(change.sources);
      if (valid === undefined) throw new Error(`cannot record invalid provenance for ${JSON.stringify(key)}`);
      outputSources[key] = valid;
    }
  }
  const sortedOutputs: Record<string, string> = {};
  for (const key of Object.keys(outputs).sort()) sortedOutputs[key] = outputs[key]!;
  const sortedSources: Record<string, ManifestOutputSource[]> = {};
  for (const key of Object.keys(outputSources).sort()) sortedSources[key] = outputSources[key]!;
  const next = {
    ...parsed,
    outputs: sortedOutputs,
  } as Manifest;
  if (Object.keys(sortedSources).length > 0) next.outputSources = sortedSources;
  else delete next.outputSources;
  return next;
}

function tryParseManifest(content: string): Partial<Manifest> | undefined {
  try {
    const parsed = JSON.parse(content) as unknown;
    return isPlainObject(parsed) ? (parsed as Partial<Manifest>) : undefined;
  } catch {
    return undefined; // corrupt previous manifest: stamp fresh, never crash a build
  }
}

/**
 * components.css emitter (plan.md §3.1) — small, tasteful UI recipes
 * (button / card / badge / table / form controls) built PURELY on the CSS
 * custom properties tokens.css defines. The hard contract (plan §3.1, Step 4
 * Done-when): ZERO literal color values — no hex, no oklch(), no rgb() — every
 * color is a var(--...) reference. Non-color literals (dimensions, 0, 1px,
 * keyword `none`) are fine; the grep gate only forbids literal colors.
 *
 * All recipes live inside `@layer components`, so a consuming app's own rules
 * (unlayered, or in a later layer) always win — the recipes are a low-priority
 * default skin, never an override the app has to fight.
 *
 * The var names referenced are the tokens.css names (raw token dot path with
 * dots -> hyphens, e.g. --color-semantic-accent, --space-4, --radius-md,
 * --shadow-elevation-1, --type-weight-semibold) — NOT the Tailwind-remapped
 * names in theme.tw.css. components.css is meant to be loaded alongside
 * tokens.css.
 *
 * The semantic/button/card/table/form recipes are a fixed template keyed on
 * the §4 semantic token set. The status BADGE variants are DERIVED from the
 * project's actual color.status groups, so adding a status token to tokens.json
 * yields a matching `.badge--<name>` with no emitter change. Determinism:
 * status order is flattenTokens enumeration order; LF, trailing newline.
 */

import type { ValidationIssue } from '../../schema/types.ts';
import { TokenValidationError } from '../../schema/validate.ts';
import { isSafeClassSuffix } from './naming.ts';
import type { EmittedFile, EmitterContext, FlatToken } from '../compile.ts';

// Re-export for existing callers/tests: the ONE implementation lives in
// naming.ts (hoisted in Step 6 — src/preview shares it; never re-declare).
export { isSafeClassSuffix } from './naming.ts';

/** DO-NOT-EDIT header, mirroring css.ts (ASCII-only, version-free). */
const HEADER = [
  '/* GENERATED by on-brand - DO NOT EDIT.',
  ' * Source of truth: brand/tokens.json (+ modes.dark.json overlay).',
  ' * Regenerate with `onbrand build`.',
  ' *',
  ' * Component recipes built purely on the tokens.css custom properties',
  ' * (load this after tokens.css). Every color is a var(--...) reference; no',
  ' * literal colors. All rules are inside @layer components so app styles win. */',
].join('\n');

/**
 * Distinct status names (in flattenTokens order) that have BOTH an fg and a bg
 * token under color.status.<name>.
 *
 * Fail-loud contract (naming.ts's project-wide rule — a silent drop is never
 * acceptable): a status name that is NOT a safe class suffix throws a
 * path-precise TokenValidationError naming the token, exactly like the
 * css/py/tw naming gates. Partial groups (fg without bg, or vice versa) are
 * deliberately NOT an error: half a pair simply cannot make a badge recipe —
 * the tokens themselves are legitimate for other consumers (tokens.css still
 * emits them) — so they are excluded from badge derivation, not failed.
 */
function statusNames(tokens: readonly FlatToken[]): string[] {
  const seen = new Map<string, { fg: boolean; bg: boolean }>();
  const order: string[] = [];
  const issues: ValidationIssue[] = [];
  const reported = new Set<string>();
  for (const token of tokens) {
    const [c, status, name, slot] = token.path;
    if (c !== 'color' || status !== 'status' || name === undefined || token.path.length !== 4) continue;
    if (!isSafeClassSuffix(name)) {
      if (!reported.has(name)) {
        reported.add(name);
        issues.push({
          path: token.dotPath,
          message:
            `status name ${JSON.stringify(name)} cannot become a badge class suffix — ` +
            'components.css derives ".badge--<name>" selectors, so color.status names ' +
            'must be non-empty and use only [A-Za-z0-9_-]; rename the status group',
        });
      }
      continue;
    }
    let entry = seen.get(name);
    if (entry === undefined) {
      entry = { fg: false, bg: false };
      seen.set(name, entry);
      order.push(name);
    }
    if (slot === 'fg') entry.fg = true;
    if (slot === 'bg') entry.bg = true;
  }
  if (issues.length > 0) {
    throw new TokenValidationError(issues, 'components.css emitter');
  }
  return order.filter((name) => {
    const entry = seen.get(name)!;
    return entry.fg && entry.bg;
  });
}

/** Emit brand/dist/components.css. */
export function emitComponents(ctx: EmitterContext): EmittedFile[] {
  const badges = statusNames(ctx.light)
    .map(
      (name) =>
        `  .badge--${name} {\n` +
        `    color: var(--color-status-${name}-fg);\n` +
        `    background: var(--color-status-${name}-bg);\n` +
        `  }`,
    )
    .join('\n');

  const body = `@layer components {
  /* --- button ------------------------------------------------------------ */
  .btn {
    display: inline-flex;
    align-items: center;
    justify-content: center;
    gap: var(--space-2);
    padding: var(--space-2) var(--space-4);
    font-family: var(--font-sans);
    font-size: var(--type-scale-step-0);
    font-weight: var(--type-weight-semibold);
    line-height: var(--type-line-height-tight);
    color: var(--color-semantic-bg);
    background: var(--color-semantic-accent);
    border: 1px solid var(--color-semantic-accent);
    border-radius: var(--radius-md);
    box-shadow: var(--shadow-elevation-1);
    cursor: pointer;
  }
  .btn:hover {
    /* Mode-adaptive hover: mixing the accent toward the (mode-flipping) text
       color darkens it in light mode and lightens it in dark mode, so the hover
       is always a visible step away from the base accent. The former
       --color-primitive-brand-10 was a fixed step that equals the accent in dark
       mode (accent maps to brand-10 there), giving primary buttons no hover
       feedback. (M1 UAT finding.) */
    background: color-mix(in oklab, var(--color-semantic-accent), var(--color-semantic-text) 14%);
    border-color: color-mix(in oklab, var(--color-semantic-accent), var(--color-semantic-text) 14%);
  }
  .btn:focus-visible {
    outline: 2px solid var(--color-semantic-accent);
    outline-offset: 2px;
  }
  .btn--secondary {
    color: var(--color-semantic-text);
    background: var(--color-semantic-surface);
    border-color: var(--color-semantic-border);
    box-shadow: none;
  }
  .btn--ghost {
    color: var(--color-semantic-accent);
    background: none;
    border: none;
    box-shadow: none;
  }

  /* --- card -------------------------------------------------------------- */
  .card {
    padding: var(--space-5);
    font-family: var(--font-sans);
    color: var(--color-semantic-text);
    background: var(--color-semantic-surface);
    border: 1px solid var(--color-semantic-border);
    border-radius: var(--radius-lg);
    box-shadow: var(--shadow-elevation-2);
  }
  .card__title {
    margin: 0 0 var(--space-2);
    font-family: var(--font-heading);
    font-size: var(--type-scale-step-1);
    font-weight: var(--type-weight-bold);
    line-height: var(--type-line-height-tight);
    color: var(--color-semantic-text);
  }

  /* --- badge ------------------------------------------------------------- */
  .badge {
    display: inline-flex;
    align-items: center;
    gap: var(--space-1);
    padding: var(--space-1) var(--space-2);
    font-family: var(--font-sans);
    font-size: var(--type-scale-step--1);
    font-weight: var(--type-weight-medium);
    line-height: var(--type-line-height-tight);
    border-radius: var(--radius-pill);
    color: var(--color-semantic-text);
    background: var(--color-semantic-code-bg);
  }
${badges}

  /* --- table ------------------------------------------------------------- */
  .table {
    width: 100%;
    border-collapse: collapse;
    font-family: var(--font-sans);
    font-size: var(--type-scale-step-0);
    color: var(--color-semantic-text);
    background: var(--color-semantic-surface);
  }
  .table th,
  .table td {
    padding: var(--space-2) var(--space-3);
    text-align: left;
    border-bottom: 1px solid var(--color-semantic-border);
  }
  .table th {
    font-weight: var(--type-weight-semibold);
    color: var(--color-semantic-text-muted);
  }
  .table tbody tr:hover {
    background: var(--color-semantic-code-bg);
  }

  /* --- form controls ----------------------------------------------------- */
  .field {
    display: flex;
    flex-direction: column;
    gap: var(--space-1);
    font-family: var(--font-sans);
  }
  .field__label {
    font-size: var(--type-scale-step--1);
    font-weight: var(--type-weight-medium);
    color: var(--color-semantic-text-muted);
  }
  .input,
  .select,
  .textarea {
    padding: var(--space-2) var(--space-3);
    font-family: var(--font-sans);
    font-size: var(--type-scale-step-0);
    color: var(--color-semantic-text);
    background: var(--color-semantic-surface);
    border: 1px solid var(--color-semantic-border);
    border-radius: var(--radius-md);
  }
  .input:focus-visible,
  .select:focus-visible,
  .textarea:focus-visible {
    outline: 2px solid var(--color-semantic-accent);
    outline-offset: 1px;
    border-color: var(--color-semantic-accent);
  }
}`;

  return [{ relPath: 'components.css', content: `${HEADER}\n\n${body}\n` }];
}

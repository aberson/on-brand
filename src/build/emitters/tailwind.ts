/**
 * theme.tw.css emitter (plan.md §3.1) — a Tailwind v4 `@theme` block mapping
 * on-brand tokens onto Tailwind's theme variable namespaces, plus companion
 * dark-override blocks.
 *
 * Namespace mapping (only namespaces VERIFIED from tailwindcss.com/docs/theme
 * are used — verification record: docs/findings/tailwind-v4-theme-namespaces.md;
 * we never invent namespaces):
 *
 *   token path            theme variable        utilities
 *   color.<...>        -> --color-<...>         bg-*, text-*, border-*, ...
 *   font.<name>        -> --font-<name>         font-sans, font-heading, ...
 *   type.size.<n> /
 *   type.scale.<n>     -> --text-<n>            text-base, text-step-1, ...
 *   type.weight.<n>    -> --font-weight-<n>     font-regular, font-bold, ...
 *   type.line-height.<n> -> --leading-<n>       leading-tight, ...
 *   space.<n>          -> --spacing-<n>         p-1, gap-2, max-h-16, ...
 *   radius.<n>         -> --radius-<n>          rounded-sm, ...
 *   shadow.<n>         -> --shadow-<n>          shadow-elevation-1, ...
 *   motion.easing.<n>  -> --ease-<n>            ease-standard, ...
 *
 * Unmapped tokens (e.g. motion.duration.* — Tailwind v4's documented theme
 * namespace table has no duration namespace) are EXCLUDED and listed in a
 * comment after the @theme block; they remain available via tokens.css.
 *
 * Dark values: Tailwind v4 @theme has no dark variant — theme variables must
 * be declared top-level (docs, verified 2026-07-16). But Tailwind emits theme
 * variables as plain custom properties on :root (inside @layer theme) and
 * compiles utilities to var() references, so this file handles dark mode by
 * re-declaring the mapped custom properties in companion UNLAYERED blocks
 * after @theme — @media (prefers-color-scheme: dark), [data-theme="dark"], then
 * a [data-theme="light"] block that reasserts the light mapped values for the
 * dark-overridden variables (so an explicit light choice wins over an OS-dark
 * match), same order/semantics as tokens.css — which win over the layered light
 * values at runtime. Consequence: do NOT convert the block to `@theme inline`
 * (inlining bakes light values into utilities and breaks the runtime flip).
 *
 * Var naming reuses tokenPathToCssVar on [namespace, ...rest] segments, so
 * sanitization matches tokens.css exactly. The namespace REMAP introduces
 * collision classes the hoisted compile.ts gate cannot see (space.1 ->
 * --spacing-1; type.weight.bold and font.weight-bold both -> --font-weight-bold),
 * so this emitter runs its own injectivity gate over the mapped names.
 */

import type { EmittedFile, EmitterContext, FlatToken } from '../compile.ts';
import { cssDeclarationValue, tokenPathToCssVar } from './css.ts';
import { assertInjectiveNames, type EmittedName } from './naming.ts';

/** DO-NOT-EDIT header, mirroring css.ts (ASCII-only, version-free). */
const HEADER = [
  '/* GENERATED by on-brand - DO NOT EDIT.',
  ' * Source of truth: brand/tokens.json (+ modes.dark.json overlay).',
  ' * Regenerate with `onbrand build`.',
  ' *',
  ' * Tailwind v4 theme variables (import after `@import "tailwindcss";`).',
  ' * The @theme block holds light values; the companion blocks below it',
  ' * re-declare the dark-overridden properties with dark values, then reassert',
  ' * their light values so an explicit light choice wins over an OS-dark match',
  ' * (all unlayered, so they win over the @layer theme light values at runtime).',
  ' * Do NOT change the block to `@theme inline` - inlining would bake light',
  ' * values into the generated utilities and break the dark flip. */',
].join('\n');

/**
 * Map a token to its Tailwind v4 theme variable name, or undefined when no
 * verified namespace covers it. Kept as data-shaped switch logic so the
 * docs-note table and this mapping stay reviewable side by side.
 */
export function tokenPathToTwVar(path: readonly string[]): string | undefined {
  const [head, ...rest] = path;
  if (rest.length === 0) return undefined; // a bare top-level token has no namespace slot
  switch (head) {
    case 'color':
      return twVar('color', rest);
    case 'font':
      return twVar('font', rest);
    case 'space':
      return twVar('spacing', rest);
    case 'radius':
      return twVar('radius', rest);
    case 'shadow':
      return twVar('shadow', rest);
    case 'type': {
      const [sub, ...tail] = rest;
      if (tail.length === 0) return undefined;
      if (sub === 'size' || sub === 'scale') return twVar('text', tail);
      if (sub === 'weight') return twVar('font-weight', tail);
      if (sub === 'line-height') return twVar('leading', tail);
      return undefined;
    }
    case 'motion': {
      const [sub, ...tail] = rest;
      if (tail.length === 0) return undefined;
      if (sub === 'easing') return twVar('ease', tail);
      return undefined; // motion.duration.*: no duration namespace in the verified table
    }
    default:
      return undefined;
  }
}

/** Same sanitization as tokens.css vars, applied to the remapped segments. */
function twVar(namespace: string, rest: readonly string[]): string {
  return tokenPathToCssVar([namespace, ...rest]);
}

interface MappedToken {
  varName: string;
  token: FlatToken;
}

function mapTokens(tokens: readonly FlatToken[]): { mapped: MappedToken[]; unmapped: FlatToken[] } {
  const mapped: MappedToken[] = [];
  const unmapped: FlatToken[] = [];
  for (const token of tokens) {
    const varName = tokenPathToTwVar(token.path);
    if (varName === undefined) {
      unmapped.push(token);
    } else {
      mapped.push({ varName, token });
    }
  }
  return { mapped, unmapped };
}

const COLLISION_HINT =
  'the Tailwind namespace remap collapsed both onto one theme variable; rename one of the two tokens';

/**
 * Injectivity gate over the REMAPPED names (see header). Exported for the
 * collision-gate unit tests.
 */
export function assertUniqueTwVarNames(tokens: readonly FlatToken[]): void {
  const entries: EmittedName[] = [];
  for (const token of tokens) {
    const varName = tokenPathToTwVar(token.path);
    if (varName === undefined) continue;
    entries.push({ name: varName, dotPath: token.dotPath, label: `token "${token.dotPath}"` });
  }
  assertInjectiveNames(entries, 'theme.tw.css emitter', COLLISION_HINT);
}

function declarations(mapped: readonly MappedToken[], indent: string): string[] {
  // cssDeclarationValue = the shared render+guard site (css.ts): a value whose
  // rendered CSS could break out of its declaration fails the build
  // path-precisely. Load-bearing here — Tailwind treats @theme as build config.
  return mapped.map(({ varName, token }) => `${indent}${varName}: ${cssDeclarationValue(token)};`);
}

/**
 * Make free text safe to interpolate into a CSS block comment: CSS comments
 * have NO escape mechanism, so a dot path containing a star-slash pair (legal
 * in token names — only "."/"{"/"}" are schema-forbidden) would close the
 * comment early. Break the pair with a space; normalize control characters to
 * spaces for the same reason.
 */
function commentSafe(text: string): string {
  let out = '';
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i);
    if (code < 0x20 || code === 0x7f) {
      out += ' ';
      continue;
    }
    if (text[i] === '*' && text[i + 1] === '/') {
      out += '* ';
      continue;
    }
    out += text[i]!;
  }
  return out;
}

/** Emit brand/dist/theme.tw.css. Throws (path-precise) on remap collisions. */
export function emitThemeTw(ctx: EmitterContext): EmittedFile[] {
  assertUniqueTwVarNames([...ctx.light, ...ctx.darkOverrides]);

  const light = mapTokens(ctx.light);
  const dark = mapTokens(ctx.darkOverrides);

  const lines: string[] = [HEADER, '', '@theme {'];
  lines.push(...declarations(light.mapped, '  '));
  lines.push('}');

  if (light.unmapped.length > 0) {
    lines.push('');
    lines.push(
      `/* Not mapped (no Tailwind v4 theme namespace; still available via tokens.css): ${commentSafe(
        light.unmapped.map((token) => token.dotPath).join(', '),
      )} */`,
    );
  }

  if (dark.mapped.length > 0) {
    lines.push('');
    lines.push('@media (prefers-color-scheme: dark) {');
    lines.push('  :root {');
    lines.push(...declarations(dark.mapped, '    '));
    lines.push('  }');
    lines.push('}');
    lines.push('');
    lines.push('[data-theme="dark"] {');
    lines.push(...declarations(dark.mapped, '  '));
    lines.push('}');
    // [data-theme="light"] reasserts the LIGHT mapped values for exactly the
    // theme variables the dark blocks override. Same fix as tokens.css: on an
    // OS in dark mode the @media block forces the dark values, and without an
    // equal-or-later light opt-in nothing can pull an explicit data-theme="light"
    // back to light (equal specificity, but the media block wins on source
    // order) — so a theme toggle appears dead. Emitted AFTER the dark blocks so
    // an explicit light choice wins over the OS preference. (M1 UAT finding.)
    const darkVarNames = new Set(dark.mapped.map((m) => m.varName));
    const lightReassert = light.mapped.filter((m) => darkVarNames.has(m.varName));
    lines.push('');
    lines.push('[data-theme="light"] {');
    lines.push(...declarations(lightReassert, '  '));
    lines.push('}');
  }

  return [{ relPath: 'theme.tw.css', content: `${lines.join('\n')}\n` }];
}

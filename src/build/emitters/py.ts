/**
 * tokens.py emitter (plan.md §3.1) — flat UPPER_SNAKE constants for Python
 * consumers (matplotlib chart styling, Jinja report templates):
 *
 *   import tokens
 *   ax.set_facecolor(tokens.COLOR_SEMANTIC_BG)
 *   ax.set_prop_cycle(color=tokens.CHART_CATEGORICAL)
 *
 * Naming: token dot path -> segments upper-snaked and joined with "_"
 * (color.semantic.text-muted -> COLOR_SEMANTIC_TEXT_MUTED; any character
 * outside [A-Za-z0-9] becomes "_"). That mapping is NOT injective —
 * color.semantic.text-muted and color.semantic.text.muted collide — so the
 * build fails path-precisely on any collision (assertInjectiveNames), never
 * silently drops a constant. A name that would start with a digit (top-level
 * group named e.g. "3d") is prefixed "N_" to stay a valid Python identifier.
 *
 * Dark-mode convention (documented in the emitted header too): DARK_<NAME>
 * exists for EVERY token — modes.dark.json overrides applied, everything not
 * overridden carrying its light value — so DARK_* is always safe to
 * reference. Both modes are always generated (plan §9.6). The DARK_ prefix is
 * part of the emitted namespace and participates in the collision gate (a
 * token group literally named "dark" can collide with it).
 *
 * CHART_CATEGORICAL / DARK_CHART_CATEGORICAL are the categorical chart colors
 * (color.chart.categorical.*) in document order, referencing the constants by
 * name so the list can never drift from them. Both names are reserved in the
 * collision gate.
 *
 * The module must import cleanly standalone: literals only, stdlib-free, no
 * imports. Values are as authored in tokens.json (strings/numbers/lists/
 * dicts); tokens.css holds the CSS-ready string forms.
 */

import type { ShadowValue, TokenValue } from '../../schema/types.ts';
import type { EmittedFile, EmitterContext, FlatToken } from '../compile.ts';
import { assertInjectiveNames, type EmittedName } from './naming.ts';

/** DO-NOT-EDIT header, mirroring css.ts (ASCII-only, version-free). */
const HEADER = [
  '# GENERATED by on-brand - DO NOT EDIT.',
  '# Source of truth: brand/tokens.json (+ modes.dark.json overlay).',
  '# Regenerate with `onbrand build`.',
  '#',
  '# One UPPER_SNAKE constant per token (dot path upper-snaked:',
  '# color.semantic.text-muted -> COLOR_SEMANTIC_TEXT_MUTED), values as',
  '# authored in tokens.json. Dark-mode convention: DARK_<NAME> exists for',
  '# EVERY token (tokens not overridden by modes.dark.json carry their light',
  '# value). CHART_CATEGORICAL / DARK_CHART_CATEGORICAL are the categorical',
  '# chart colors in order. Standalone module: literals only, no imports.',
].join('\n');

const DARK_PREFIX = 'DARK_';
const CHART_LIST_NAME = 'CHART_CATEGORICAL';
const CATEGORICAL_PATH_PREFIX = ['color', 'chart', 'categorical'];

/** token dot-path segments -> UPPER_SNAKE Python constant name. */
export function tokenPathToPyName(segments: readonly string[]): string {
  const joined = segments
    .map((segment) => segment.replaceAll(/[^A-Za-z0-9]/g, '_'))
    .join('_')
    .toUpperCase();
  // A leading digit is not a valid Python identifier start.
  return /^[0-9]/.test(joined) ? `N_${joined}` : joined;
}

function isShadowObject(value: TokenValue): value is ShadowValue {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/** Render a token $value as a Python literal (single line; values are small). */
export function tokenValueToPy(value: TokenValue): string {
  if (typeof value === 'string') return JSON.stringify(value); // valid Python string syntax
  if (typeof value === 'number') return String(value);
  if (Array.isArray(value)) {
    return `[${value.map((item) => tokenValueToPy(item as TokenValue)).join(', ')}]`;
  }
  if (isShadowObject(value)) {
    // Fixed key order = the ShadowValue contract (validate.ts is strict:
    // exactly these five keys), same canonical order css.ts prints.
    return (
      '{' +
      `"color": ${JSON.stringify(value.color)}, ` +
      `"offsetX": ${JSON.stringify(value.offsetX)}, ` +
      `"offsetY": ${JSON.stringify(value.offsetY)}, ` +
      `"blur": ${JSON.stringify(value.blur)}, ` +
      `"spread": ${JSON.stringify(value.spread)}` +
      '}'
    );
  }
  // Unreachable for validated documents; fail loud rather than emit garbage.
  throw new Error(`tokens.py emitter: unsupported token value ${JSON.stringify(value)}`);
}

const COLLISION_HINT =
  'dots, hyphens, and other separators all map to "_" in UPPER_SNAKE names ' +
  '(and DARK_/CHART_CATEGORICAL are reserved); rename one of the two';

/**
 * Build-time uniqueness gate over the FULL emitted namespace: light names,
 * their DARK_-prefixed counterparts, and the reserved list constants.
 * Exported for the collision-gate unit tests.
 */
export function assertUniquePyNames(tokens: readonly FlatToken[]): void {
  const entries: EmittedName[] = [
    {
      name: CHART_LIST_NAME,
      dotPath: CATEGORICAL_PATH_PREFIX.join('.'),
      label: `the reserved list constant ${CHART_LIST_NAME}`,
    },
    {
      name: `${DARK_PREFIX}${CHART_LIST_NAME}`,
      dotPath: CATEGORICAL_PATH_PREFIX.join('.'),
      label: `the reserved list constant ${DARK_PREFIX}${CHART_LIST_NAME}`,
    },
  ];
  for (const token of tokens) {
    entries.push({
      name: tokenPathToPyName(token.path),
      dotPath: token.dotPath,
      label: `token "${token.dotPath}"`,
    });
  }
  for (const token of tokens) {
    entries.push({
      name: `${DARK_PREFIX}${tokenPathToPyName(token.path)}`,
      dotPath: token.dotPath,
      label: `the dark-mode constant of token "${token.dotPath}"`,
    });
  }
  assertInjectiveNames(entries, 'tokens.py emitter', COLLISION_HINT);
}

function isCategorical(token: FlatToken): boolean {
  return (
    token.path.length === CATEGORICAL_PATH_PREFIX.length + 1 &&
    CATEGORICAL_PATH_PREFIX.every((segment, i) => token.path[i] === segment)
  );
}

function constantLines(
  tokens: readonly FlatToken[],
  valueFor: (t: FlatToken) => TokenValue,
  prefix: string,
): string[] {
  return tokens.map(
    (token) => `${prefix}${tokenPathToPyName(token.path)} = ${tokenValueToPy(valueFor(token))}`,
  );
}

function chartListLines(tokens: readonly FlatToken[], prefix: string): string[] {
  const names = tokens
    .filter(isCategorical)
    .map((token) => `${prefix}${tokenPathToPyName(token.path)}`);
  if (names.length === 0) return [`${prefix}${CHART_LIST_NAME} = []`];
  return [`${prefix}${CHART_LIST_NAME} = [`, ...names.map((name) => `    ${name},`), ']'];
}

/** Emit brand/dist/tokens.py. Throws (path-precise) on name collisions. */
export function emitTokensPy(ctx: EmitterContext): EmittedFile[] {
  assertUniquePyNames(ctx.light);

  const darkValues = new Map<string, TokenValue>(
    ctx.darkOverrides.map((token) => [token.dotPath, token.value]),
  );
  const darkValueFor = (token: FlatToken): TokenValue =>
    darkValues.get(token.dotPath) ?? token.value;

  const lines: string[] = [
    HEADER,
    '',
    '# --- light -----------------------------------------------------------------',
    '',
    ...constantLines(ctx.light, (token) => token.value, ''),
    '',
    ...chartListLines(ctx.light, ''),
    '',
    '# --- dark ------------------------------------------------------------------',
    '',
    ...constantLines(ctx.light, darkValueFor, DARK_PREFIX),
    '',
    ...chartListLines(ctx.light, DARK_PREFIX),
  ];
  return [{ relPath: 'tokens.py', content: `${lines.join('\n')}\n` }];
}

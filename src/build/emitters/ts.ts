/**
 * theme.ts emitter (plan.md §3.1) — typed constant tree mirroring token paths,
 * for inline-style React / React Native code:
 *
 *   import { theme, darkTheme } from './brand/dist/theme';
 *   <div style={{ background: theme.color.semantic.bg }} />
 *
 * Shape (the dark-mode convention, documented in the emitted header too):
 *   - `theme`     — the FULL light tree, keys are the EXACT token/group names
 *     nested exactly as in tokens.json (color.semantic.bg ->
 *     theme.color.semantic.bg; hyphenated names via brackets:
 *     theme.color.semantic["text-muted"]).
 *   - `darkTheme` — a FULL parallel tree of the same shape holding dark-mode
 *     values: modes.dark.json overrides applied, everything not overridden
 *     identical to light. Both modes are always generated (plan §9.6); with no
 *     modes.dark.json, darkTheme carries the light values.
 *   Two complete trees (rather than per-token {light,dark} leaves) keep leaf
 *   access ergonomic (a leaf IS the value) and let consumers flip modes by
 *   swapping one root object.
 *
 * Typing: both trees are `as const`, so consumers get readonly literal types
 * ("#fcfcfd", not string). Values are emitted AS AUTHORED in tokens.json
 * (strings/numbers/arrays/shadow objects) — tokens.css / theme.tw.css hold the
 * CSS-ready string forms.
 *
 * Naming/injectivity: keys are the exact token names in the exact group
 * nesting — no normalization — so the mapping is injective by construction
 * (JSON keys are unique within a group, and validated leaves are never
 * prefixes of other leaves). The flattened emitters (py, tw, css) normalize
 * and therefore carry collision gates; this one does not need to.
 *
 * Determinism: tree insertion order comes from ctx.light (flattenTokens
 * enumeration order), keys are rendered in insertion order, LF, trailing
 * newline.
 */

import type { ShadowValue, TokenValue } from '../../schema/types.ts';
import type { EmittedFile, EmitterContext, FlatToken } from '../compile.ts';

/** DO-NOT-EDIT header, mirroring css.ts (ASCII-only, version-free). */
const HEADER = [
  '/* GENERATED by on-brand - DO NOT EDIT.',
  ' * Source of truth: brand/tokens.json (+ modes.dark.json overlay).',
  ' * Regenerate with `onbrand build`.',
  ' *',
  ' * `theme` holds light values; `darkTheme` is the same shape with dark-mode',
  ' * values (tokens not overridden by modes.dark.json carry their light value).',
  ' * Keys are the exact token names from tokens.json - hyphenated names are',
  ' * quoted, so use bracket access: theme.color.semantic["text-muted"].',
  ' * Values are as authored (tokens.css holds the CSS-ready string forms). */',
].join('\n');

/** Bare-identifier keys stay unquoted for dot access readability. */
const IDENTIFIER_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function renderKey(name: string): string {
  return IDENTIFIER_RE.test(name) ? name : JSON.stringify(name);
}

function isShadowObject(value: TokenValue): value is ShadowValue {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/** Render a token $value as a TS literal (single line; values are small). */
export function tokenValueToTs(value: TokenValue): string {
  if (typeof value === 'string') return JSON.stringify(value);
  if (typeof value === 'number') return String(value);
  if (Array.isArray(value)) {
    return `[${value.map((item) => tokenValueToTs(item as TokenValue)).join(', ')}]`;
  }
  if (isShadowObject(value)) {
    // Fixed key order = the ShadowValue contract (validate.ts is strict:
    // exactly these five keys), same canonical order css.ts prints.
    return (
      '{ ' +
      `color: ${JSON.stringify(value.color)}, ` +
      `offsetX: ${JSON.stringify(value.offsetX)}, ` +
      `offsetY: ${JSON.stringify(value.offsetY)}, ` +
      `blur: ${JSON.stringify(value.blur)}, ` +
      `spread: ${JSON.stringify(value.spread)}` +
      ' }'
    );
  }
  // Unreachable for validated documents; fail loud rather than emit garbage.
  throw new Error(`theme.ts emitter: unsupported token value ${JSON.stringify(value)}`);
}

// A tree node is either a group (Map preserves pure insertion order — the
// flattenTokens enumeration order that reaches us) or a leaf value.
type TreeNode = Map<string, TreeNode> | { value: TokenValue };

function buildTree(tokens: readonly FlatToken[], valueFor: (t: FlatToken) => TokenValue): TreeNode {
  const root: Map<string, TreeNode> = new Map();
  for (const token of tokens) {
    let node = root;
    for (const segment of token.path.slice(0, -1)) {
      let child = node.get(segment);
      if (child === undefined || !(child instanceof Map)) {
        // (non-Map is unreachable: validated leaves are never group prefixes)
        child = new Map<string, TreeNode>();
        node.set(segment, child);
      }
      node = child;
    }
    node.set(token.path[token.path.length - 1]!, { value: valueFor(token) });
  }
  return root;
}

function renderNode(node: TreeNode, indent: string): string {
  if (!(node instanceof Map)) return tokenValueToTs(node.value);
  const inner = `${indent}  `;
  const lines: string[] = ['{'];
  for (const [name, child] of node) {
    lines.push(`${inner}${renderKey(name)}: ${renderNode(child, inner)},`);
  }
  lines.push(`${indent}}`);
  return lines.join('\n');
}

/** Emit brand/dist/theme.ts. */
export function emitThemeTs(ctx: EmitterContext): EmittedFile[] {
  const darkValues = new Map<string, TokenValue>(
    ctx.darkOverrides.map((token) => [token.dotPath, token.value]),
  );

  const lightTree = buildTree(ctx.light, (token) => token.value);
  const darkTree = buildTree(ctx.light, (token) => darkValues.get(token.dotPath) ?? token.value);

  const lines: string[] = [
    HEADER,
    '',
    `export const theme = ${renderNode(lightTree, '')} as const;`,
    '',
    `export const darkTheme = ${renderNode(darkTree, '')} as const;`,
    '',
    'export type Theme = typeof theme;',
    'export type DarkTheme = typeof darkTheme;',
  ];
  return [{ relPath: 'theme.ts', content: `${lines.join('\n')}\n` }];
}

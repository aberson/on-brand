/**
 * tokens.css emitter (plan.md §3.1).
 *
 * Shape:
 *   @layer tokens {
 *     :root { --color-semantic-bg: ...; ... }                        // light values, all tokens
 *     @media (prefers-color-scheme: dark) { :root { ... } }          // dark overrides only
 *     [data-theme="dark"]  { ... }                                   // same dark overrides
 *     [data-theme="light"] { ... }                                   // light values for the dark-overridden tokens
 *   }
 *
 * Block order is load-bearing: within the layer all four selectors tie on
 * specificity against the html element, so source order lets the explicit
 * [data-theme="dark"] / [data-theme="light"] opt-ins win over both the light
 * base and the OS media preference. The [data-theme="light"] block exists so an
 * explicit light choice can override an OS-dark media match (without it a theme
 * toggle is dead on a dark-mode OS — M1 finding). Dark/light opt-in blocks are
 * omitted entirely when there are no overrides.
 *
 * Var naming: token dot path -> custom property (dots -> hyphens), e.g.
 * color.semantic.bg -> --color-semantic-bg. Any character not valid in a CSS
 * ident is normalized to "-" (schema names never contain "."/"{"/"}", but a
 * space is schema-legal and would break a custom property name).
 *
 * That mapping is deliberately human-readable but NOT injective: "." and a
 * literal "-" inside a name both land on "-" (color.semantic.text-muted and
 * color.semantic.text.muted would share one var). assertUniqueVarNames() is
 * the build-time gate: any collision fails the build with a path-precise
 * error naming both tokens — never a silent last-declared-wins drop.
 *
 * Values pass through as authored (plan.md §9.10 — the default preset holds
 * hex today; an oklch() $value would pass through unchanged), but only after
 * the declaration-safety guard (cssDeclarationValue below): a value whose
 * rendered CSS could break out of its declaration fails the build. Composite
 * types are printed in their canonical CSS form (shadow lists,
 * cubic-bezier()).
 */

import type {
  TokenType,
  TokenValue,
  ShadowValue,
  CubicBezierValue,
  ValidationIssue,
} from '../../schema/types.ts';
import { TokenValidationError } from '../../schema/validate.ts';
import type { EmittedFile, EmitterContext, FlatToken } from '../compile.ts';

/** DO-NOT-EDIT header (plan.md §3.1). Version-free to keep rebuild diffs
 * source-driven; ASCII-only so byte-compares never trip on encoding. */
const HEADER = [
  '/* GENERATED by on-brand - DO NOT EDIT.',
  ' * Source of truth: brand/tokens.json (+ modes.dark.json overlay).',
  ' * Regenerate with `onbrand build`. */',
].join('\n');

/** token dot-path segments -> CSS custom property name. */
export function tokenPathToCssVar(segments: readonly string[]): string {
  const joined = segments.join('-');
  return `--${joined.replaceAll(/[^a-zA-Z0-9_-]/g, '-')}`;
}

/**
 * Build-time uniqueness gate for the non-injective var-name mapping: distinct
 * dot paths that collapse onto one custom property (e.g.
 * color.semantic.text-muted vs color.semantic.text.muted) fail the build with
 * a path-precise error naming BOTH tokens. Without this, the later
 * declaration would silently shadow the earlier one.
 */
export function assertUniqueVarNames(tokens: readonly FlatToken[]): void {
  const seen = new Map<string, string>(); // varName -> first dotPath
  const reported = new Set<string>();
  const issues: ValidationIssue[] = [];
  for (const token of tokens) {
    const varName = tokenPathToCssVar(token.path);
    const existing = seen.get(varName);
    if (existing === undefined) {
      seen.set(varName, token.dotPath);
      continue;
    }
    // Same dot path twice is fine (dark overrides re-visit their base token).
    if (existing === token.dotPath) continue;
    const dedupeKey = `${varName} ${token.dotPath}`;
    if (reported.has(dedupeKey)) continue;
    reported.add(dedupeKey);
    issues.push({
      path: token.dotPath,
      message: `CSS custom property ${varName} collides with token "${existing}" — dots and hyphens both map to "-" in var names; rename one of the two tokens`,
    });
  }
  if (issues.length > 0) {
    throw new TokenValidationError(issues, 'tokens.css emitter');
  }
}

function isShadowValue(value: unknown): value is ShadowValue {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

export function shadowToCss(shadow: ShadowValue): string {
  // box-shadow order: offset-x offset-y blur-radius spread-radius color
  return `${shadow.offsetX} ${shadow.offsetY} ${shadow.blur} ${shadow.spread} ${shadow.color}`;
}

/**
 * CSS-string-escape a font family name's contents (issue #20). Backslash and
 * double-quote are the two characters that break a double-quoted CSS string:
 * a `$value` ending in a lone backslash would otherwise render `"Foo\"` — an
 * UNTERMINATED string that makes the WHOLE emitted file unparseable (postcss
 * reports it) while the build still exits 0. We escape rather than reject so a
 * site-derived font stack (from-url feeds these into tokens, Steps 11-12)
 * round-trips as a valid, terminated string instead of silently corrupting the
 * file. Order is load-bearing: escape the backslash FIRST, so the backslash a
 * quote-escape introduces is not itself doubled. Char literals only — no
 * control bytes (repo text-hygiene gate).
 */
function cssEscapeStringContent(name: string): string {
  return name.replaceAll('\\', '\\\\').replaceAll('"', '\\"');
}

/** Quote a font family name unless it is a safe CSS ident (keywords stay bare).
 * Quoted names are CSS-string-escaped (cssEscapeStringContent) so a name
 * carrying a quote or backslash round-trips safely (issue #20). A legitimate
 * quoted stack ("Segoe UI", "JetBrains Mono") contains neither, so escaping is
 * a no-op and byte-for-byte output is unchanged vs. golden. */
function fontFamilyName(name: string): string {
  return /^[a-zA-Z][a-zA-Z0-9-]*$/.test(name) ? name : `"${cssEscapeStringContent(name)}"`;
}

function cubicBezierToCss(value: CubicBezierValue): string {
  return typeof value === 'string' ? value : `cubic-bezier(${value.join(', ')})`;
}

/** Convert a token $value to its CSS text for a custom property. */
export function tokenValueToCss(type: TokenType, value: TokenValue): string {
  switch (type) {
    case 'color':
      // TODO(Step 10, plan §9.10): when ramps.ts lands OKLCH ramp generation,
      // add the hex-fallback seam here — an oklch() $value should emit as
      // `oklch(...)` with a computed sRGB hex fallback declaration. Until
      // then, colors pass through exactly as authored (hex today).
      return String(value);
    case 'dimension':
    case 'duration':
      return String(value);
    case 'fontWeight':
    case 'number':
      return String(value);
    case 'fontFamily':
      return Array.isArray(value)
        ? (value as string[]).map(fontFamilyName).join(', ')
        : fontFamilyName(String(value));
    case 'cubicBezier':
      return cubicBezierToCss(value as CubicBezierValue);
    case 'shadow':
      if (Array.isArray(value)) {
        return (value as ShadowValue[]).map(shadowToCss).join(', ');
      }
      return isShadowValue(value) ? shadowToCss(value) : String(value);
  }
}

/**
 * Find the first sequence in a rendered CSS value that could break out of its
 * declaration: ";" ends the declaration, "{" / "}" escape the block, the
 * two comment delimiters (slash-star, star-slash) open/close comments, and
 * control characters (code < 0x20 — tab/newline included — plus DEL 0x7F)
 * have no place in a one-line declaration. Implemented with explicit char
 * codes, NOT a regex character class: this repo's authoring pipeline has
 * repeatedly corrupted escape sequences into raw control bytes (see
 * test/repo.text-hygiene.test.ts), and numeric literals cannot be corrupted
 * that way.
 *
 * Returns a human-readable description of the offending sequence, or
 * undefined when the value is clean.
 */
function findForbiddenCssSequence(css: string): string | undefined {
  for (let i = 0; i < css.length; i++) {
    const code = css.charCodeAt(i);
    if (code < 0x20 || code === 0x7f) {
      return `control character (code ${code})`;
    }
    const ch = css[i]!;
    if (ch === ';' || ch === '{' || ch === '}') return `"${ch}"`;
    if (ch === '/' && css[i + 1] === '*') return 'comment delimiter "/*"';
    if (ch === '*' && css[i + 1] === '/') return 'comment delimiter "*' + '/"';
  }
  return undefined;
}

/**
 * Render a token's CSS declaration value, refusing (path-precise) any value
 * whose rendered text could escape the declaration. The ONE render+guard site
 * for every CSS-emitting path (tokens.css AND theme.tw.css — higher stakes
 * there: Tailwind treats @theme as build configuration, and from-url (Steps
 * 11-12) will feed site-derived values into tokens; fetched content is data,
 * never structure, per the workspace security rule). Schema validation does
 * NOT close this hole: colorSchema/dimensionSchema accept any "fn(...)"
 * string ending in ")" and fontFamily accepts any non-empty string.
 *
 * Checked on the RENDERED CSS text so composite values (shadow lists, font
 * stacks) are covered uniformly. Legitimate values (hex, oklch()/clamp()
 * expressions, quoted font names with commas) never contain these sequences.
 * Rejection, not escaping, is deliberate: CSS custom-property values have no
 * escape mechanism that survives var() substitution unchanged, and no §4
 * token class needs these characters.
 */
export function cssDeclarationValue(token: FlatToken): string {
  const css = tokenValueToCss(token.type, token.value);
  const forbidden = findForbiddenCssSequence(css);
  if (forbidden !== undefined) {
    throw new TokenValidationError(
      [
        {
          path: token.dotPath,
          message:
            `value renders to CSS containing forbidden ${forbidden} — ` +
            'token values may not contain ";", "{", "}", comment delimiters, ' +
            'or control characters (they would break out of the emitted CSS declaration)',
        },
      ],
      'css value guard',
    );
  }
  return css;
}

function declarations(tokens: readonly FlatToken[], indent: string): string[] {
  return tokens.map(
    (token) => `${indent}${tokenPathToCssVar(token.path)}: ${cssDeclarationValue(token)};`,
  );
}

/** Emit brand/dist/tokens.css. Throws (path-precise) on var-name collisions. */
export function emitTokensCss(ctx: EmitterContext): EmittedFile[] {
  assertUniqueVarNames([...ctx.light, ...ctx.darkOverrides]);

  const lines: string[] = [HEADER, '', '@layer tokens {', '  :root {'];
  lines.push(...declarations(ctx.light, '    '));
  lines.push('  }');

  if (ctx.darkOverrides.length > 0) {
    lines.push('');
    lines.push('  @media (prefers-color-scheme: dark) {');
    lines.push('    :root {');
    lines.push(...declarations(ctx.darkOverrides, '      '));
    lines.push('    }');
    lines.push('  }');
    lines.push('');
    lines.push('  [data-theme="dark"] {');
    lines.push(...declarations(ctx.darkOverrides, '    '));
    lines.push('  }');
    // [data-theme="light"] reasserts the LIGHT values for exactly the tokens the
    // dark override changes. Without it, on an OS in dark mode the media query
    // forces :root dark and nothing can pull an explicit data-theme="light" back
    // to light (equal specificity, but the media block wins on source order) —
    // so a theme toggle appears dead. Emitted AFTER the media block so an
    // explicit light choice wins over the OS preference. (M1 UAT finding.)
    const darkVarNames = new Set(ctx.darkOverrides.map((t) => tokenPathToCssVar(t.path)));
    const lightReassert = ctx.light.filter((t) => darkVarNames.has(tokenPathToCssVar(t.path)));
    lines.push('');
    lines.push('  [data-theme="light"] {');
    lines.push(...declarations(lightReassert, '    '));
    lines.push('  }');
  }

  lines.push('}');
  return [{ relPath: 'tokens.css', content: `${lines.join('\n')}\n` }];
}
